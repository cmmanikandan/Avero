export function getBrandBySlug(slug) {
  if (!slug) return null;
  const target = String(slug).toLowerCase().trim();
  const slugClean = target.replace(/\s+/g, '-');

  // 1. Direct match in built-in directory
  const found = BRAND_DIRECTORY.find(
    b => b.slug === target || b.slug === slugClean || b.name.toLowerCase() === target || b.name.toLowerCase().replace(/\s+/g, '-') === slugClean
  );
  if (found) return found;

  // 2. Match custom seller brand stores from LocalStorage
  try {
    const customStores = JSON.parse(localStorage.getItem('avero_brand_stores') || '[]');
    const customMatch = customStores.find(
      s => s.slug === target || s.slug === slugClean || s.name?.toLowerCase() === target || s.name?.toLowerCase().replace(/\s+/g, '-') === slugClean
    );
    if (customMatch) {
      return {
        id: `br-${customMatch.slug || customMatch.name}`,
        name: customMatch.name,
        slug: customMatch.slug || customMatch.name.toLowerCase().replace(/\s+/g, '-'),
        logo: customMatch.logo || 'https://images.unsplash.com/photo-1556742049-0cfed4f6a45d?w=200&q=80',
        banner: customMatch.banner || 'https://images.unsplash.com/photo-1550009158-9ebf69173e03?w=1400&q=80',
        tagline: customMatch.tagline || 'Verified Marketplace Brand Partner',
        category: customMatch.category || 'Electronics & Lifestyle',
        rating: customMatch.rating || 4.8,
        reviewsCount: customMatch.reviewsCount || 120,
        followerCount: customMatch.followerCount || '18K',
        verified: true,
        accentColor: '#3B82F6',
        description: customMatch.description || `Welcome to the official ${customMatch.name} brand storefront.`
      };
    }
  } catch (_) {}

  // 3. Return null if not found (Never force-fallback to Apple!)
  return null;
}
